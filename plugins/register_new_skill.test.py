"""Unit tests for TDD/Fast-Track skill generation and registration guards."""

from core.plugin_loader import PluginLoader
from plugins.register_new_skill import RegisterNewSkill

PLUGIN_TEMPLATE = """
from typing import Any, Dict

from core.base_plugin import BaseAgentPlugin
from core.schemas import PluginOutputSchema, StrictBaseModel


class Input(StrictBaseModel):
    text: str


class GeneratedPlugin(BaseAgentPlugin):
    plugin_name = "{name}"
    description = "Generated by a test."
    input_schema = Input

    def initialize(self, config: Dict[str, Any]) -> bool:
        return True

    def execute(self, payload: Dict[str, Any]) -> PluginOutputSchema:
        return PluginOutputSchema(success=True, data=payload)

    def shutdown(self) -> None:
        return None
"""

TEST_SOURCE = "def test_generated():\n    assert True\n"


def _payload(name="generated_echo", mode="TDD", test_source=TEST_SOURCE):
    return {
        "skill_name": name,
        "description": "Echo generated skill.",
        "source": PLUGIN_TEMPLATE.format(name=name),
        "test_source": test_source,
        "mode": mode,
    }


def test_tdd_failure_does_not_register_plugin(tmp_path):
    runner_calls = []

    def failing_runner(test_path):
        runner_calls.append(test_path)
        return False

    plugin = RegisterNewSkill(plugins_dir=tmp_path, test_runner=failing_runner)

    result = plugin.execute(_payload())

    assert result.success is False
    assert "test" in result.error_message.lower()
    assert len(runner_calls) == 1
    assert not (tmp_path / "generated_echo.py").exists()
    assert not (tmp_path / "generated_echo.test.py").exists()
    assert PluginLoader(tmp_path).load_all() == {}


def test_tdd_pass_registers_plugin(tmp_path):
    plugin = RegisterNewSkill(plugins_dir=tmp_path, test_runner=lambda path: True)

    result = plugin.execute(_payload())

    assert result.success is True
    assert result.data["plugin_name"] == "generated_echo"
    assert (tmp_path / "generated_echo.py").exists()
    loaded = PluginLoader(tmp_path).load_all()
    assert "generated_echo" in loaded


def test_fast_track_skips_tests_and_registers_plugin(tmp_path):
    def runner_must_not_run(test_path):
        raise AssertionError("Fast-Track must not run tests")

    plugin = RegisterNewSkill(plugins_dir=tmp_path, test_runner=runner_must_not_run)

    result = plugin.execute(_payload(mode="FAST_TRACK", test_source=None))

    assert result.success is True
    assert "generated_echo" in PluginLoader(tmp_path).load_all()


def test_tdd_requires_test_source(tmp_path):
    plugin = RegisterNewSkill(plugins_dir=tmp_path, test_runner=lambda path: True)

    result = plugin.execute(_payload(test_source=None))

    assert result.success is False
    assert "test_source" in result.error_message
    assert not (tmp_path / "generated_echo.py").exists()


def test_approval_gate_can_reject_generated_plugin(tmp_path):
    plugin = RegisterNewSkill(
        plugins_dir=tmp_path,
        test_runner=lambda path: True,
        approver=lambda name, source: False,
    )

    result = plugin.execute(_payload())

    assert result.success is False
    assert "approval" in result.error_message.lower()
    assert not (tmp_path / "generated_echo.py").exists()
    assert not (tmp_path / "generated_echo.test.py").exists()


def test_approval_gate_can_allow_generated_plugin(tmp_path):
    plugin = RegisterNewSkill(
        plugins_dir=tmp_path,
        test_runner=lambda path: True,
        approver=lambda name, source: True,
    )

    result = plugin.execute(_payload())

    assert result.success is True
    assert "generated_echo" in PluginLoader(tmp_path).load_all()


def test_invalid_plugin_source_is_not_registered(tmp_path):
    plugin = RegisterNewSkill(plugins_dir=tmp_path, test_runner=lambda path: True)
    payload = _payload()
    payload["source"] = "class NotAPlugin:\n    pass\n"

    result = plugin.execute(payload)

    assert result.success is False
    assert not (tmp_path / "generated_echo.py").exists()